// Writes source/app/sw-files.js: the app-shell file list and cache version used by source/app/sw.js.
//   node work/tools/gen-sw-files.mjs          (run it after adding, removing or renaming a file under source/app/; CI runs it too)
// The version is a hash of every listed file's bytes, so a changed file means a new cache and an "Update available" toast.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import path from "node:path";

export const PUBLIC = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../source/app");
// Not part of the shell: the SW itself and its list (the browser tracks those), licence text, markers.
const SKIP = new Set(["sw.js", "sw-files.js", ".nojekyll", "fonts/OFL.txt", "fonts/README.md"]);
const SHELL = /\.(html|css|js|json|webmanifest|woff2|png|svg|ico)$/;
const walk = (dir, rel = "") => readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
  const r = rel ? `${rel}/${e.name}` : e.name;
  return e.isDirectory() ? walk(path.join(dir, e.name), r) : [r];
});
/** Every file the app can load, as paths relative to source/app/ (sorted). */
export const collect = () => walk(PUBLIC).filter((f) => !SKIP.has(f) && SHELL.test(f)).sort();
export const versionOf = (files) => {
  const hash = createHash("sha256");
  for (const f of files) hash.update(f).update("\0").update(readFileSync(path.join(PUBLIC, f))).update("\0");
  return hash.digest("hex").slice(0, 12);
};
export function render(files = collect()) {
  return `// Generated by work/tools/gen-sw-files.mjs. Do not edit by hand.
// APP_FILES is the precached app shell (index.html is the start page); APP_VERSION names the cache (a hash of the files).
self.APP_VERSION = ${JSON.stringify(versionOf(files))};
self.APP_FILES = ${JSON.stringify(files, null, 2)};
`;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const files = collect();
  writeFileSync(path.join(PUBLIC, "sw-files.js"), render(files));
  console.log(`sw-files.js: ${files.length} files, version ${versionOf(files)}`);
}
